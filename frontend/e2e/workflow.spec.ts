import { test, expect } from '@playwright/test';
test('session, catalog persistence, Pending amendment, delivery and forbidden writes', async ({page}) => {
  if (process.env['JEDEL_ISOLATED_BROWSER'] !== '1') throw new Error('Use the guarded backend browser test runner; never target a project database.');
  const businessRequests: string[] = [];
  page.on('request', request => { if (/\/api\/(products|suppliers|orders|analytics|dashboard|access)\//.test(request.url())) businessRequests.push(request.url()); });
  await page.goto('/');
  await expect(page).toHaveURL(/\/$/);
  await expect(page.getByRole('heading', {name: 'Purchasing, made simple.'})).toBeVisible();
  for (const name of ['Suppliers', 'Orders', 'Analytics', 'Products']) {
    await page.getByRole('navigation').getByRole('link', {name, exact: true}).click();
    if (name === 'Products') {
      await expect(page.getByRole('heading', {name: 'Public catalog hardware', exact: true})).toBeVisible();
      await expect(page.getByText('Unit price', {exact: true})).toHaveCount(0);
    } else await expect(page.getByRole('heading', {name: 'Open your team workspace', exact: true})).toBeVisible();
  }
  expect(businessRequests).toEqual([]);
  await page.getByRole('link', {name: 'Create product', exact: true}).click();
  await expect(page).toHaveURL(/auth\?mode=login&returnTo=/);

  await page.getByLabel('Email address or username', {exact: true}).fill('browser-manager');
  await page.getByLabel('Password', {exact: true}).fill(process.env['JEDEL_E2E_PASSWORD']!);
  await page.locator('form').getByRole('button', {name: 'Log in', exact: true}).click();
  await expect(page).toHaveURL(/products\/new/);
  await expect(page.locator('.account-summary')).toContainText('Purchasing Manager');
  await expect(page.getByRole('heading', {name: 'New product', exact: true})).toBeVisible();
  await page.getByRole('button', {name: 'Cancel', exact: true}).click();
  await page.getByRole('navigation', {name: 'Main navigation'}).getByRole('link', {name: 'Suppliers', exact: true}).click();
  await page.getByRole('button', {name: 'New supplier', exact: true}).click();
  await page.getByLabel('Supplier name', {exact: true}).fill('Browser supplier');
  await page.getByLabel('Email', {exact: true}).fill('browser-supplier@example.test');
  await page.getByRole('button', {name: 'Save supplier', exact: true}).click();
  await expect(page.getByRole('heading', {name: 'Browser supplier', exact: true})).toBeVisible();
  await page.getByRole('navigation', {name: 'Main navigation'}).getByRole('link', {name: 'Products', exact: true}).click();
  await page.getByRole('button', {name: 'New product', exact: true}).click();
  await page.getByLabel('Product name', {exact: true}).fill('Browser product');
  await page.getByLabel('Category', {exact: true}).last().fill('Browser');
  await page.getByLabel('Unit price', {exact: true}).fill('12.50');
  await page.getByRole('button', {name: 'Save product', exact: true}).click();
  await expect(page.getByRole('heading', {name: 'Browser product', exact: true})).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', {name: 'Browser product', exact: true})).toBeVisible();
  await page.getByRole('navigation', {name: 'Main navigation'}).getByRole('link', {name: 'Orders', exact: true}).click();
  await page.getByRole('button', {name: 'New order', exact: true}).click();
  await page.getByRole('combobox', {name: 'Supplier', exact: true}).selectOption({label: 'Browser supplier'});
  const productSelect = page.getByRole('combobox', {name: 'Product 1', exact: true});
  await productSelect.selectOption({label: await productSelect.locator('option').filter({hasText: /^\s*Browser product\s/}).innerText()});
  await page.getByLabel('Quantity 1', {exact: true}).fill('2');
  await page.getByRole('button', {name: 'Create order', exact: true}).click();
  await expect(page.getByRole('button', {name: 'Edit Pending order'})).toBeVisible();
  await page.getByRole('button', {name: 'Edit Pending order'}).click();
  await page.getByLabel('Quantity 1', {exact: true}).fill('3');
  await page.getByRole('button', {name: 'Save amendment'}).click();
  await expect(page.getByRole('button', {name: 'Edit Pending order'})).toBeVisible();
  await page.getByRole('button', {name: 'Mark Approved'}).click();
  await expect(page.locator('.detail')).toContainText('Approved');
  await page.getByRole('button', {name: 'Mark Delivered'}).click();
  await expect(page.locator('.detail')).toContainText('Delivered');
  await expect(page.locator('.detail')).toContainText('37.50');
  await page.getByRole('navigation', {name: 'Main navigation'}).getByRole('link', {name: 'Products', exact: true}).click();
  await expect(page.locator('article').filter({has: page.getByRole('heading', {name: 'Browser product', exact: true})})).toContainText('3 units');
  await page.getByRole('navigation', {name: 'Main navigation'}).getByRole('link', {name: 'Analytics', exact: true}).click();
  await expect(page.getByRole('table')).toContainText('37.50');
  await page.locator('.profile-menu summary').click();
  await page.locator('.profile-dropdown').getByRole('link', {name: 'Settings', exact: true}).click();
  await page.getByRole('button', {name: 'Sign out', exact: true}).click();
  await expect(page).toHaveURL(/auth\?mode=login/);
  await page.getByLabel('Email address or username', {exact: true}).fill('browser-viewer');
  await page.getByLabel('Password', {exact: true}).fill(process.env['JEDEL_E2E_PASSWORD']!);
  await page.locator('form').getByRole('button', {name: 'Log in', exact: true}).click();
  await expect(page.locator('.account-summary')).toContainText('browser-viewer');
  await expect(page).toHaveURL(/\/$/);
  await page.getByRole('navigation', {name: 'Main navigation'}).getByRole('link', {name: 'Products', exact: true}).click();
  await expect(page.getByRole('heading', {name: 'Browser product', exact: true})).toBeVisible();
  await expect(page.getByRole('button', {name: 'New product', exact: true})).toHaveCount(0);
  const result = await page.evaluate(async () => {
    await fetch('/api/auth/csrf/');
    const csrf = document.cookie.split('; ').find(v => v.startsWith('csrftoken='))?.split('=')[1] ?? '';
    return (await fetch('/api/products/', {method: 'POST', headers: {'Content-Type': 'application/json', 'X-CSRFToken': csrf}, body: JSON.stringify({product_name: 'Forbidden', unit_price: '1.00'})})).status;
  });
  expect(result).toBe(403);
  await page.goto('/products/new');
  await expect(page.getByRole('heading', {name: 'Access denied', exact: true})).toBeVisible();
});
