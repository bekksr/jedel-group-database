import { test, expect } from '@playwright/test';
test('registration activates Basic User, logs in automatically, persists and preserves restrictions', async ({page, browser}) => {
  if (process.env['JEDEL_ISOLATED_BROWSER'] !== '1') throw new Error('Use the isolated backend harness.');
  const password = process.env['JEDEL_E2E_PASSWORD']!;
  await page.goto('/register');
  await page.getByLabel('Full name', {exact: true}).fill('Browser Applicant');
  await page.getByLabel('Email address', {exact: true}).fill('browser-applicant@example.test');
  await page.getByLabel('Password', {exact: true}).fill(password);
  await page.getByLabel('Confirm password', {exact: true}).fill(password);
  await page.locator('form').getByRole('button', {name: 'Register', exact: true}).click();
  await expect(page.getByRole('heading', {name: 'Purchasing, made simple.'})).toBeVisible();
  await expect(page.getByText('Account created successfully. Welcome to Jedel.Group!', {exact: true})).toBeVisible();
  await expect(page.locator('.account-summary')).toContainText('Browser Applicant');
  await expect(page.locator('.account-summary')).toContainText('Basic User');
  await page.reload();
  await expect(page.locator('.account-summary')).toContainText('Browser Applicant');
  const me = await page.request.get('/api/auth/me/');
  expect(me.status()).toBe(200);
  const account = await me.json(); expect(account.role).toBe('Basic User'); expect(account.can_administer).toBe(false);
  expect(Object.values(account.capabilities).some(Boolean)).toBe(false);
  expect((await page.request.get('/api/suppliers/')).status()).toBe(403);
  expect((await page.request.get('/api/orders/')).status()).toBe(403);
  await page.getByRole('navigation').getByRole('link', {name: 'Products', exact: true}).click();
  await expect(page.getByRole('heading', {name: 'Public catalog hardware', exact: true})).toBeVisible();
  await expect(page.getByText('Unit price', {exact: true})).toHaveCount(0);
  await expect(page.getByText('Warehouse stock', {exact: true})).toHaveCount(0);
  await expect(page.getByRole('button', {name: 'Edit', exact: true})).toHaveCount(0);
  await page.getByLabel('Search products', {exact: true}).fill('office');
  await expect(page.getByRole('heading', {name: 'Public catalog office', exact: true})).toBeVisible();
  await expect(page.getByRole('heading', {name: 'Public catalog hardware', exact: true})).toHaveCount(0);
  await page.getByLabel('Search products', {exact: true}).fill('');
  await page.getByRole('combobox', {name: 'Category', exact: true}).selectOption('Hardware');
  await expect(page.getByRole('heading', {name: 'Public catalog hardware', exact: true})).toBeVisible();
  await expect(page.getByRole('heading', {name: 'Public catalog office', exact: true})).toHaveCount(0);
  const safeCatalog = await page.request.get('/api/catalog/products/');
  const safeRows = (await safeCatalog.json()).results;
  for (const row of safeRows) expect(Object.keys(row).sort()).toEqual(['category','product_id','product_name']);
  await page.goto('/products/new');
  await expect(page.getByRole('heading', {name: 'Access denied', exact: true})).toBeVisible();
  await page.locator('.profile-menu summary').click();
  await expect(page.getByRole('link', {name: 'My Profile', exact: true})).toBeVisible();
  await page.getByRole('button', {name: 'Log out', exact: true}).click();
  await expect(page.getByRole('navigation').getByRole('link', {name: 'Account', exact: true})).toBeVisible();
  expect((await page.request.get('/api/auth/me/')).status()).toBe(401);
  await page.goto('/login');
  await page.getByLabel('Email address or username', {exact: true}).fill('browser-applicant@example.test');
  await page.getByLabel('Password', {exact: true}).fill(password);
  await page.locator('form').getByRole('button', {name: 'Log in', exact: true}).click();
  await expect(page.locator('.account-summary')).toContainText('Basic User');
  const adminContext = await browser.newContext();
  const admin = await adminContext.newPage();
  const backend = process.env['JEDEL_E2E_BACKEND_URL']!;
  await admin.goto(backend + '/admin/login/?next=/admin/');
  await admin.getByLabel(/^Username/).fill('browser-admin');
  await admin.getByLabel(/^Password/).fill(password);
  await admin.getByRole('button', {name: 'Log in', exact: true}).click();
  await expect(admin.getByText('Accounts, catalog and purchasing workflows', {exact: true})).toBeVisible();
  await admin.goto(backend + '/admin/purchasing/product/add/');
  await admin.getByLabel(/^Product name/).fill('Admin browser product');
  await admin.getByLabel(/^Category/).fill('Admin verified');
  await admin.getByLabel(/^Unit price/).fill('4.25');
  await expect(admin.locator('input[name="stock_quantity"]')).toHaveCount(0);
  await admin.getByRole('button', {name: 'Save', exact: true}).click();
  await expect(admin.getByRole('link', {name: 'Admin browser product', exact: true})).toBeVisible();
  await adminContext.close();
  await page.locator('.profile-menu summary').click();
  await page.getByRole('link', {name: 'My Profile', exact: true}).click();
  await expect(page.getByRole('heading', {name: 'Account settings', exact: true})).toBeVisible();
  await page.locator('.profile-menu summary').click();
  await page.getByRole('button', {name: 'Log out', exact: true}).click();
  await page.getByRole('navigation').getByRole('link', {name: 'Home', exact: true}).click();
  await expect(page.getByRole('heading', {name: 'Purchasing, made simple.'})).toBeVisible();
  await expect(page.locator('.account-summary')).toHaveCount(0);
});
